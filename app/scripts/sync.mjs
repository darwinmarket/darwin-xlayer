#!/usr/bin/env node
/**
 * Keeps the app in step with the rest of the repository, with one source of truth for each:
 *   circuits/src/{netlist,darwin}.ts   -> app/src/circuits/   (the TAP-02 builder, simulator, Darwin's circuits)
 *   contracts/out/<Name>.sol/<Name>.json -> app/src/abi/<Name>.ts (ABIs, after `forge build`)
 *   deployments/<name>.json            -> app/src/config/deployments.ts
 * Every output is committed, so the app builds where Foundry is not installed (the copies are
 * only refreshed when their source exists). Run with --check to fail if a copy is out of date.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(app, "..");
const check = process.argv.includes("--check");
let stale = 0;

function write(path, content) {
  const old = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (old === content) return;
  if (check) {
    console.error(`out of date: ${path.slice(app.length + 1)}`);
    stale++;
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`sync: ${path.slice(app.length + 1)}`);
}

// ---- circuits --------------------------------------------------------------------------------
for (const f of ["netlist.ts", "darwin.ts"]) {
  const src = join(root, "circuits", "src", f);
  if (!existsSync(src)) continue;
  const header = `// Generated by app/scripts/sync.mjs from circuits/src/${f}. Do not edit: change the source and run \`npm run sync\`.\n`;
  write(join(app, "src", "circuits", f), header + readFileSync(src, "utf8"));
}

// ---- ABIs --------------------------------------------------------------------------------------
const abis = {
  DarwinOracle: "DarwinOracle.sol/DarwinOracle.json",
  DarwinGuard: "DarwinGuard.sol/DarwinGuard.json",
  DarwinBasket: "DarwinBasket.sol/DarwinBasket.json",
  DarwinRouter: "DarwinRouter.sol/DarwinRouter.json",
  DarwinStudio: "DarwinStudio.sol/DarwinStudio.json",
  TapeoutProcessor: "External.sol/ITapeoutProcessor.json",
  ERC20: "IERC20Metadata.sol/IERC20Metadata.json",
};
const out = join(root, "contracts", "out");
for (const [name, rel] of Object.entries(abis)) {
  const src = join(out, rel);
  if (!existsSync(src)) continue;
  const abi = JSON.parse(readFileSync(src, "utf8")).abi;
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  write(
    join(app, "src", "abi", `${name}.ts`),
    `// Generated by app/scripts/sync.mjs from contracts/out/${rel}. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}

// ---- deployments -------------------------------------------------------------------------------
const depDir = join(root, "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).sort()) {
    if (!f.endsWith(".json")) continue;
    try {
      deployments[f.replace(/\.json$/, "")] = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    } catch (e) {
      console.warn(`sync: skipping deployments/${f}: ${e.message}`);
    }
  }
}
const depOut = join(app, "src", "config", "deployments.ts");
if (Object.keys(deployments).length > 0 || !existsSync(depOut)) {
  write(
    depOut,
    `// Generated by app/scripts/sync.mjs from deployments/*.json. Do not edit.\nimport type { DeploymentFile } from "@/lib/deployment-types";\n\nexport const DEPLOYMENTS: Record<string, DeploymentFile> = ${JSON.stringify(deployments, null, 2)};\n`,
  );
}

if (check && stale) {
  console.error(`${stale} file(s) out of date: run npm run sync`);
  process.exit(1);
}
